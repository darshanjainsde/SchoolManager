/** A whole printable document — what the phone hands to expo-print. */
export function receiptHtml(r: FeeReceiptDoc): string {
  return `<!doctype html><html><head><meta charset="utf-8"><title>Receipt ${esc(r.number)}</title><style>@page{size:A5;margin:14mm}body{margin:0}${RECEIPT_CSS}</style></head><body>${receiptBody(r)}</body></html>`;
}
