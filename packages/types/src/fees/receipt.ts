/**
 * THE RECEIPT, AS A DOCUMENT — one HTML page shared by the web (printed
 * through the print portal) and the app (printed to a PDF on the phone).
 * Literal ink, millimetres, hairlines: it is paper in both themes.
 */
export interface FeeReceiptDoc {
  number: string;
  issuedAt: string;
  amountMinor: number;
  method: string;
  providerRef: string | null;
  paidOn: string;
  verifiedAt: string | null;
  termName: string | null;
  invoiceNumber: string | null;
  student: { name: string; admissionNo: string; className: string | null };
  school: { name: string };
}

const esc = (v: unknown) =>
  String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] as string);

const METHOD: Record<string, string> = {
  UPI: 'UPI', NEFT_IMPS: 'NEFT / IMPS', CHEQUE: 'Cheque', CASH: 'Cash at office', CARD: 'Card', NETBANKING: 'Net banking', OTHER: 'Other',
};

/** ₹24,500 — Indian grouping, paise only when there are any. */
export function receiptRupees(amountMinor: number): string {
  const abs = Math.abs(amountMinor);
  const whole = Math.floor(abs / 100);
  const paise = abs % 100;
  const s = String(whole);
  const grouped = s.length <= 3 ? s : `${s.slice(0, -3).replace(/\B(?=(\d{2})+(?!\d))/g, ',')},${s.slice(-3)}`;
  return `${amountMinor < 0 ? '−' : ''}₹${paise === 0 ? grouped : `${grouped}.${String(paise).padStart(2, '0')}`}`;
}

const day = (iso: string) =>
  new Date(iso).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'Asia/Kolkata' });

/** The receipt's BODY markup — the web wraps it in its print portal, the app in a full document. */
export function receiptBody(r: FeeReceiptDoc): string {
  return `<div class="rcpt">
  <div class="rcpt-head"><h1>${esc(r.school.name)}</h1><div class="rcpt-kind">Fee receipt</div></div>
  <div class="rcpt-stamp">PAID</div>
  <div class="rcpt-amt">${esc(receiptRupees(r.amountMinor))}</div>
  <table class="rcpt-facts">
    <tr><th>Receipt no.</th><td>${esc(r.number)}</td></tr>
    <tr><th>Received from</th><td>${esc(r.student.name)}${r.student.className ? ` · ${esc(r.student.className)}` : ''} · Adm. ${esc(r.student.admissionNo)}</td></tr>
    ${r.termName ? `<tr><th>Towards</th><td>${esc(r.termName)}${r.invoiceNumber ? ` · ${esc(r.invoiceNumber)}` : ''}</td></tr>` : ''}
    <tr><th>Paid on</th><td>${esc(day(r.paidOn))} · ${esc(METHOD[r.method] ?? r.method)}${r.providerRef ? ` · ref ${esc(r.providerRef)}` : ''}</td></tr>
    <tr><th>Confirmed</th><td>${r.verifiedAt ? esc(day(r.verifiedAt)) : '—'}</td></tr>
  </table>
  <div class="rcpt-foot">Issued ${esc(day(r.issuedAt))} · Generated by Sckools — valid without a signature.</div>
</div>`;
}

